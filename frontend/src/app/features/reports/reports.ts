export class ReportsPage {
  private readonly api = inject(Api);
  protected readonly locale = inject(Locale);
  protected readonly session = inject(Session);
  private readonly toast = inject(Toast);

  protected readonly canExport = this.session.can('reports.export');
  protected readonly types: GeneratedReport['report_type'][] = ['rse_summary', 'waste_register', 'economic_balance'];
  protected readonly type = signal<GeneratedReport['report_type']>('rse_summary');
  protected readonly format = signal<'pdf' | 'xlsx'>('pdf');
  /** Language of the document: the user's own by default, changeable for this report. */
  protected readonly language = signal(this.locale.documents());
  protected readonly period = signal<Period>(presetPeriod('year'));
  protected readonly busy = signal(false);
  protected polling = false;
  protected readonly list = new ListStore<GeneratedReport>((query) => this.api.list<GeneratedReport>('reports', query));

  protected readonly columns: Column<GeneratedReport>[] = [
    { key: 'type', header: 'reports.type' },
    { key: 'format', header: 'reports.format' },
    { key: 'requested', header: 'reports.requested', hideBelow: 640 },
    { key: 'expires', header: 'reports.expires', hideBelow: 900 },
    { key: 'status', header: 'fields.status' },
    { key: 'actions', header: 'common.actions' },
  ];

  constructor() {
    // While a report is being built, look again every few seconds; stop as soon as none is pending.
    const timer = setInterval(() => {
      this.polling = this.list.rows().some((report) => report.status === 'queued' || report.status === 'processing');
      if (this.polling) {
        this.list.reload();
      }
    }, 4000);
    inject(DestroyRef).onDestroy(() => clearInterval(timer));
    this.loadSchedules();
  }

  /** R-01: the usual reports, with their period and format chosen. */
  protected readonly presets: { key: string; icon: string; type: GeneratedReport['report_type']; format: 'pdf' | 'xlsx'; period: () => Period }[] = [
    { key: 'rseYear', icon: 'eco', type: 'rse_summary', format: 'pdf', period: () => presetPeriod('year') },
    { key: 'registerMonth', icon: 'menu_book', type: 'waste_register', format: 'xlsx', period: () => lastMonth() },
    { key: 'balanceQuarter', icon: 'payments', type: 'economic_balance', format: 'pdf', period: () => presetPeriod('quarter') },
  ];

  protected readonly schedules = signal<{ ulid: string; report_type: string; format: string }[]>([]);

  protected scheduleOf(preset: { type: string; format: string }): { ulid: string } | undefined {
    return this.schedules().find((item) => item.report_type === preset.type && item.format === preset.format);
  }

  protected async schedule(preset: { type: GeneratedReport['report_type']; format: 'pdf' | 'xlsx' }, on: boolean): Promise<void> {
    try {
      const existing = this.scheduleOf(preset);
      if (on && !existing) {
        await firstValueFrom(this.api.post('report-schedules', { report_type: preset.type, format: preset.format, lang: this.language() }));
        this.toast.success('reports.monthlyOn');
      } else if (!on && existing) {
        await firstValueFrom(this.api.delete(`report-schedules/${existing.ulid}`));
        this.toast.success('reports.monthlyOff');
      }
    } catch (error) {
      this.toast.error(error);
    }
    this.loadSchedules();
  }

  private loadSchedules(): void {
    if (this.canExport) {
      this.api.get<{ ulid: string; report_type: string; format: string }[]>('report-schedules').subscribe({ next: (rows) => this.schedules.set(rows), error: () => undefined });
    }
  }

  protected quick(preset: { type: GeneratedReport['report_type']; format: 'pdf' | 'xlsx'; period: () => Period }): void {
    this.type.set(preset.type);
    this.format.set(preset.format);
    this.period.set(preset.period());
    void this.generate();
  }

  protected async generate(): Promise<void> {
    this.busy.set(true);
    try {
      await firstValueFrom(this.api.post('reports', { report_type: this.type(), format: this.format(), lang: this.language(), ...this.period() }));
      this.toast.success('reports.queued');
      this.list.setPage(1, this.list.perPage());
    } catch (error) {
      this.toast.error(error);
    } finally {
      this.busy.set(false);
    }
  }

  protected async download(report: GeneratedReport): Promise<void> {
    try {
      const blob = await firstValueFrom(this.api.blob(`reports/${report.ulid}/download`));
      openBlob(blob, `${report.report_type}-${report.parameters.from}-${report.parameters.to}.${report.format}`);
    } catch (error) {
      this.toast.error(error);
    }
  }
}
